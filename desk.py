"""
Research Desk: seven analysts argue a ticker, then the composite formula decides.

Deliberately importable without Streamlit so it can be tested directly
(see test_desk.py), the same way scoring.py is.

HOW THE DESK WORKS
------------------
  1. Tape Reader         — the four technical z-scores from scoring.py.
  2. Fundamentals Analyst — valuation, quality and analyst targets. Context only:
                           your composite formula does not score fundamentals,
                           so these points carry zero formula weight.
  3. News Analyst        — the recency-weighted headline tone.
  4. Bull Advocate       — collects the strongest positive evidence.
  5. Bear Advocate       — collects the strongest negative evidence.
  6. Risk Manager        — VaR, Expected Shortfall, drawdown, ATR-based sizing.
  7. Backtest Gate       — will not let anything through unless the score beat
                           holding the stock (and the index, when given) on the
                           most recent slice of history, net of trading costs.

  The Chief then rules. The ruling is NOT a vote count and NOT the louder
  advocate. It is your composite score (scoring.combine) and the gate:

      gate fails                -> "No trade. Hold the index."
      gate passes, score >= +0.5 -> paper-trade candidate, sized by risk
      gate passes, score <= -0.5 -> avoid / reduce (never a short instruction)
      otherwise                 -> no clear tilt, no action

WHAT "ARGUING" MEANS HERE
-------------------------
Each agent is deterministic: the same data always produces the same argument.
Nothing is generated by a language model, so nothing can be invented. Every
claim is traceable to a number on screen, and every number that feeds the
ruling comes from your formula.

STATISTICAL NOTES
-----------------
* The gate trades on yesterday's score (position is lagged one day), so the
  backtest never uses a reading before it could have been known.
* Nothing is fitted on the in-sample slice: the threshold is the formula's own
  +0.5 sigma "mildly positive" line, fixed before any data is seen. That is
  what makes the recent slice genuinely out-of-sample. If you move the
  sliders after looking at the gate's answer, you are tuning on that slice
  and it stops being out-of-sample. The UI says so.
* The p-value is the circular block bootstrap from scoring.backtest, run on
  the out-of-sample slice only.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

import scoring

TRADING_DAYS = 252


# ----------------------------------------------------------------------
# DATA STRUCTURES
# ----------------------------------------------------------------------
@dataclass
class Argument:
    """One point an agent makes.

    `weight` is the point's contribution in the formula's own units. Points
    the formula does not score (fundamentals, risk observations) have weight
    0.0 and `scored=False`, so the Chief cannot be swayed by them.
    """
    side: str            # "bull" | "bear" | "neutral"
    claim: str
    evidence: str
    weight: float = 0.0
    scored: bool = False
    source: str = ""


@dataclass
class AgentReport:
    name: str
    role: str
    stance: str          # "bull" | "bear" | "neutral"
    summary: str
    arguments: list[Argument] = field(default_factory=list)
    metrics: dict = field(default_factory=dict)


@dataclass
class DeskConfig:
    oos_fraction: float = 0.30          # most recent share of history held out
    min_oos_days: int = 120
    cost_bps: float = 10.0              # per side, applied on every position change
    entry_threshold: float | None = None  # defaults to scoring's mild threshold
    p_threshold: float = 0.10
    min_entries: int = 3
    risk_per_trade_pct: float = 1.0     # % of capital lost if the stop is hit
    stop_atr_multiple: float = 2.0
    max_position_pct: float = 20.0
    var_confidence: float = 0.95


DESK_CFG = DeskConfig()


def _fmt_pct(x, digits=1):
    return "n/a" if x is None or not np.isfinite(x) else f"{x:+.{digits}f}%"


def _finite(x) -> bool:
    return x is not None and np.isfinite(x)


def _stance(value: float | None, cfg: scoring.ScoringConfig) -> str:
    if not _finite(value):
        return "neutral"
    if value >= cfg.mild_threshold:
        return "bull"
    if value <= -cfg.mild_threshold:
        return "bear"
    return "neutral"


# ----------------------------------------------------------------------
# 1. TAPE READER
# ----------------------------------------------------------------------
_COMPONENT_WORDS = {
    "trend": ("50-day average above 200-day", "50-day average below 200-day"),
    "momentum": ("RSI running hot versus its own history", "RSI weak versus its own history"),
    "band_position": ("price stretched toward the top of its band", "price pressed toward the bottom of its band"),
    "volume": ("volume arriving on up days", "volume arriving on down days"),
}


def tape_reader(indicator_frame: pd.DataFrame, technical: float | None,
                weights_used: dict, cfg: scoring.ScoringConfig = scoring.CFG) -> AgentReport:
    """Reads the four technical z-scores and prices each in formula units.

    A component's weight is its share of the technical blend times the
    technical weight actually used in the composite. These are pre-
    standardisation shares, so they explain direction and relative size
    rather than summing exactly to the final number.
    """
    w_tech = weights_used.get("technical", 0.0)
    total_sw = sum(cfg.tech_subweights.values())
    last = indicator_frame.iloc[-1] if len(indicator_frame) else pd.Series(dtype=float)

    args = []
    metrics = {}
    for key, sw in cfg.tech_subweights.items():
        z = last.get(f"z_{key}", np.nan)
        metrics[f"z_{key}"] = float(z) if _finite(z) else None
        if not _finite(z):
            continue
        up_word, down_word = _COMPONENT_WORDS.get(key, (key, key))
        side = "bull" if z > 0 else "bear" if z < 0 else "neutral"
        args.append(Argument(
            side=side,
            claim=up_word if z > 0 else down_word,
            evidence=f"{scoring.COMPONENT_LABELS.get(key, key)}: z = {z:+.2f}",
            weight=float(w_tech * (sw / total_sw) * z),
            scored=True,
            source="Tape Reader",
        ))

    stance = _stance(technical, cfg)
    reading, _ = scoring.describe_reading(technical, cfg) if _finite(technical) else ("Not enough data", "")
    summary = (f"Technical score {technical:+.2f} sigma: {reading.lower()}."
               if _finite(technical) else "Not enough price history to read the tape.")
    metrics["technical"] = technical
    return AgentReport("Tape Reader", "Technicals", stance, summary, args, metrics)


# ----------------------------------------------------------------------
# 2. FUNDAMENTALS ANALYST (context only — zero formula weight)
# ----------------------------------------------------------------------
def fundamentals_analyst(fund: dict, price: float | None) -> AgentReport:
    """Valuation, quality and analyst view. Never scored by the formula."""
    fund = fund or {}
    args: list[Argument] = []

    def add(side, claim, evidence):
        args.append(Argument(side, claim, evidence, 0.0, False, "Fundamentals Analyst"))

    roe = fund.get("return_on_equity")
    if _finite(roe):
        if roe >= 0.15:
            add("bull", "High return on equity", f"ROE {roe * 100:.1f}%")
        elif roe < 0.05:
            add("bear", "Weak return on equity", f"ROE {roe * 100:.1f}%")

    margin = fund.get("operating_margins")
    if _finite(margin):
        if margin >= 0.20:
            add("bull", "Strong operating margin", f"{margin * 100:.1f}%")
        elif margin < 0:
            add("bear", "Losing money at the operating line", f"{margin * 100:.1f}%")

    growth = fund.get("revenue_growth")
    if _finite(growth):
        if growth >= 0.10:
            add("bull", "Revenue growing quickly", f"{growth * 100:+.1f}% year on year")
        elif growth < 0:
            add("bear", "Revenue shrinking", f"{growth * 100:+.1f}% year on year")

    de = fund.get("debt_to_equity")
    if _finite(de):
        # yfinance reports this as a percentage (150 = 1.5x).
        if de > 200:
            add("bear", "Heavy leverage", f"debt/equity {de / 100:.1f}x")
        elif de < 50:
            add("bull", "Light balance sheet", f"debt/equity {de / 100:.1f}x")

    tpe, fpe = fund.get("trailing_pe"), fund.get("forward_pe")
    if _finite(tpe) and _finite(fpe) and tpe > 0 and fpe > 0:
        if fpe < tpe * 0.85:
            add("bull", "Earnings expected to grow into the multiple",
                f"forward P/E {fpe:.1f} vs trailing {tpe:.1f}")
        elif fpe > tpe * 1.15:
            add("bear", "Earnings expected to fall", f"forward P/E {fpe:.1f} vs trailing {tpe:.1f}")
    if _finite(tpe) and tpe > 40:
        add("bear", "Rich valuation", f"trailing P/E {tpe:.1f}")

    target, n_analysts = fund.get("target_mean_price"), fund.get("num_analyst_opinions")
    if _finite(target) and _finite(price) and price > 0:
        upside = (target / price - 1) * 100
        who = f" ({int(n_analysts)} analysts)" if _finite(n_analysts) else ""
        if upside >= 10:
            add("bull", "Analysts see upside", f"mean target {upside:+.0f}% from here{who}")
        elif upside <= -5:
            add("bear", "Price already above analyst targets", f"mean target {upside:+.0f}% from here{who}")

    bulls = sum(a.side == "bull" for a in args)
    bears = sum(a.side == "bear" for a in args)
    stance = "bull" if bulls > bears else "bear" if bears > bulls else "neutral"
    if not args:
        summary = "Not enough fundamental data to form a view."
    else:
        summary = (f"{bulls} supportive and {bears} cautionary points. Context only: "
                   "your formula does not score fundamentals.")
    return AgentReport("Fundamentals Analyst", "Fundamentals (unscored)", stance, summary, args,
                       {"bull_points": bulls, "bear_points": bears})


# ----------------------------------------------------------------------
# 3. NEWS ANALYST
# ----------------------------------------------------------------------
def news_analyst(sentiment_sigma: float | None, sentiment_info: dict | None,
                 weights_used: dict, cfg: scoring.ScoringConfig = scoring.CFG) -> AgentReport:
    if sentiment_sigma is None or not sentiment_info:
        return AgentReport("News Analyst", "Headlines", "neutral",
                           "No headlines to read, so sentiment is dropped from the formula.",
                           [], {"sentiment": None})
    w = weights_used.get("sentiment", 0.0)
    side = "bull" if sentiment_sigma > 0 else "bear" if sentiment_sigma < 0 else "neutral"
    tone = "positive" if side == "bull" else "negative" if side == "bear" else "balanced"
    arg = Argument(
        side=side,
        claim=f"Recent headlines read {tone}",
        evidence=(f"tone {sentiment_sigma:+.2f} sigma from {sentiment_info['n_items']} headlines "
                  f"(effective n {sentiment_info['effective_n']:.1f}, newest "
                  f"{sentiment_info['newest_age_hours']:.0f}h old)"),
        weight=float(w * sentiment_sigma),
        scored=True,
        source="News Analyst",
    )
    summary = (f"Headline tone {sentiment_sigma:+.2f} sigma after shrinking for a small sample.")
    return AgentReport("News Analyst", "Headlines", _stance(sentiment_sigma, cfg), summary, [arg],
                       {"sentiment": sentiment_sigma})


# ----------------------------------------------------------------------
# 4 & 5. ADVOCATES
# ----------------------------------------------------------------------
def _advocate(side: str, reports: list[AgentReport], top_n: int = 5) -> AgentReport:
    pool = [a for r in reports for a in r.arguments if a.side == side]
    # Scored points first, largest formula weight first, then unscored context.
    pool.sort(key=lambda a: (not a.scored, -abs(a.weight)))
    chosen = pool[:top_n]
    strength = float(sum(abs(a.weight) for a in pool if a.scored))
    name = "Bull Advocate" if side == "bull" else "Bear Advocate"
    role = "Argues for" if side == "bull" else "Argues against"
    if not chosen:
        summary = "Nothing in the data supports this side right now."
    else:
        n_scored = sum(a.scored for a in pool)
        summary = (f"{len(pool)} points ({n_scored} scored by your formula), "
                   f"formula weight {strength:.2f}.")
    return AgentReport(name, role, side, summary, chosen,
                       {"strength": strength, "n_points": len(pool)})


def bull_advocate(reports: list[AgentReport]) -> AgentReport:
    return _advocate("bull", reports)


def bear_advocate(reports: list[AgentReport]) -> AgentReport:
    return _advocate("bear", reports)


# ----------------------------------------------------------------------
# 6. RISK MANAGER
# ----------------------------------------------------------------------
def _max_drawdown(close: pd.Series) -> float:
    if close.empty:
        return float("nan")
    peak = close.cummax()
    return float((close / peak - 1).min())


def risk_manager(daily_df: pd.DataFrame, indicator_frame: pd.DataFrame,
                 risk_penalty: float, desk_cfg: DeskConfig = DESK_CFG) -> AgentReport:
    """Sizes the downside. Sizing is illustrative, a % of a hypothetical account.

    Position size = risk budget / stop distance, where the stop sits
    `stop_atr_multiple` ATRs below the price. Capped, then cut by the macro
    haircut so a nervous market shrinks the size as well as the conviction.
    """
    close = daily_df["Close"].dropna()
    rets = close.pct_change().dropna()
    last_year = rets.iloc[-TRADING_DAYS:]
    metrics: dict = {}
    args: list[Argument] = []

    if len(last_year) < 30:
        return AgentReport("Risk Manager", "Downside & sizing", "neutral",
                           "Not enough history to size risk.", [], {})

    alpha = 1 - desk_cfg.var_confidence
    var = float(-np.quantile(last_year, alpha))
    tail = last_year[last_year <= -var]
    es = float(-tail.mean()) if len(tail) else var
    ann_vol = float(last_year.std() * np.sqrt(TRADING_DAYS))
    mdd = _max_drawdown(close.iloc[-TRADING_DAYS:])
    price = float(close.iloc[-1])
    atr = indicator_frame["ATR"].iloc[-1] if "ATR" in indicator_frame else np.nan
    atr_pct = float(atr / price) if _finite(atr) and price > 0 else float("nan")

    metrics.update({
        "var_1d_pct": var * 100, "es_1d_pct": es * 100, "ann_vol_pct": ann_vol * 100,
        "max_drawdown_1y_pct": mdd * 100, "atr_pct": atr_pct * 100 if _finite(atr_pct) else None,
        "price": price,
    })

    if _finite(atr_pct) and atr_pct > 0:
        stop_dist = desk_cfg.stop_atr_multiple * atr_pct
        raw_size = desk_cfg.risk_per_trade_pct / (stop_dist * 100) * 100
        size = min(raw_size, desk_cfg.max_position_pct) * (1 - risk_penalty)
        metrics.update({
            "stop_distance_pct": stop_dist * 100,
            "stop_price": price * (1 - stop_dist),
            "position_pct": float(size),
            "position_capped": raw_size > desk_cfg.max_position_pct,
        })
    else:
        metrics["position_pct"] = None

    def note(side, claim, evidence):
        args.append(Argument(side, claim, evidence, 0.0, False, "Risk Manager"))

    if ann_vol > 0.50:
        note("bear", "Very volatile", f"annualised volatility {ann_vol * 100:.0f}%")
    if mdd < -0.30:
        note("bear", "Deep drawdown in the past year", f"max drawdown {mdd * 100:.0f}%")
    if risk_penalty >= 0.15:
        note("bear", "Market is nervous", f"macro haircut −{risk_penalty * 100:.0f}% on conviction")
    if ann_vol < 0.20 and mdd > -0.15:
        note("bull", "Calm risk profile", f"vol {ann_vol * 100:.0f}%, drawdown {mdd * 100:.0f}%")

    if metrics.get("position_pct") is not None:
        summary = (f"Worst 5% of days lose {var * 100:.1f}% or more (average {es * 100:.1f}% "
                   f"when it happens). At {desk_cfg.risk_per_trade_pct:.1f}% risk with a "
                   f"{desk_cfg.stop_atr_multiple:.0f}×ATR stop, size would be "
                   f"{metrics['position_pct']:.1f}% of the account.")
    else:
        summary = f"Worst 5% of days lose {var * 100:.1f}% or more."
    return AgentReport("Risk Manager", "Downside & sizing", "neutral", summary, args, metrics)


# ----------------------------------------------------------------------
# 7. BACKTEST GATE
# ----------------------------------------------------------------------
def _perf(daily_returns: pd.Series) -> dict:
    r = daily_returns.dropna()
    if r.empty:
        return {"total_pct": float("nan"), "ann_pct": float("nan"), "vol_pct": float("nan"),
                "sharpe": float("nan"), "max_dd_pct": float("nan")}
    equity = (1 + r).cumprod()
    total = float(equity.iloc[-1] - 1)
    years = len(r) / TRADING_DAYS
    ann = float((1 + total) ** (1 / years) - 1) if years > 0 and total > -1 else float("nan")
    vol = float(r.std() * np.sqrt(TRADING_DAYS))
    sharpe = float(r.mean() / r.std() * np.sqrt(TRADING_DAYS)) if r.std() > 0 else 0.0
    return {"total_pct": total * 100, "ann_pct": ann * 100, "vol_pct": vol * 100,
            "sharpe": sharpe, "max_dd_pct": _max_drawdown(equity) * 100}


def gate_strategy_returns(score: pd.Series, close: pd.Series, threshold: float,
                          cost_bps: float) -> pd.DataFrame:
    """Long when YESTERDAY's score cleared the threshold, flat otherwise.

    The one-day lag is the whole point: a score stamped at today's close can
    only be acted on from tomorrow.
    """
    frame = pd.concat([score.rename("score"), close.rename("close")], axis=1).dropna()
    frame["ret"] = frame["close"].pct_change()
    frame["pos"] = (frame["score"] >= threshold).astype(float).shift(1).fillna(0.0)
    turnover = frame["pos"].diff().abs().fillna(frame["pos"].abs())
    frame["strat"] = frame["pos"] * frame["ret"] - turnover * cost_bps / 1e4
    frame["entry"] = (frame["pos"].diff() > 0).astype(int)
    return frame.dropna(subset=["ret"])


def backtest_gate(score: pd.Series, close: pd.Series,
                  index_close: pd.Series | None = None,
                  cfg: scoring.ScoringConfig = scoring.CFG,
                  desk_cfg: DeskConfig = DESK_CFG) -> AgentReport:
    threshold = desk_cfg.entry_threshold if desk_cfg.entry_threshold is not None else cfg.mild_threshold
    frame = gate_strategy_returns(score, close, threshold, desk_cfg.cost_bps)
    n = len(frame)
    split = int(n * (1 - desk_cfg.oos_fraction))
    oos = frame.iloc[split:]
    ins = frame.iloc[:split]

    metrics: dict = {"threshold": threshold, "cost_bps": desk_cfg.cost_bps,
                     "n_days": n, "n_oos_days": len(oos)}
    checks: list[tuple[str, bool, str]] = []

    enough = len(oos) >= desk_cfg.min_oos_days
    checks.append(("Enough unseen data", enough,
                   f"{len(oos)} out-of-sample days (need {desk_cfg.min_oos_days})"))

    if not enough:
        metrics["checks"] = checks
        metrics["passed"] = False
        return AgentReport("Backtest Gate", "Out-of-sample test", "bear",
                           "Blocked: not enough history to test the score on data it never saw.",
                           [Argument("bear", "Cannot prove an edge", checks[0][2], 0.0, False, "Backtest Gate")],
                           metrics)

    strat_oos, hold_oos = _perf(oos["strat"]), _perf(oos["ret"])
    strat_ins, hold_ins = _perf(ins["strat"]), _perf(ins["ret"])
    metrics.update({"oos_strategy": strat_oos, "oos_hold": hold_oos,
                    "is_strategy": strat_ins, "is_hold": hold_ins,
                    "oos_entries": int(oos["entry"].sum()),
                    "oos_exposure_pct": float(oos["pos"].mean() * 100),
                    "oos_start": str(oos.index[0].date()), "oos_end": str(oos.index[-1].date())})

    checks.append(("Beats holding the stock, risk-adjusted",
                   strat_oos["sharpe"] > hold_oos["sharpe"],
                   f"Sharpe {strat_oos['sharpe']:.2f} vs {hold_oos['sharpe']:.2f}"))

    if index_close is not None and not index_close.dropna().empty:
        idx = index_close.reindex(oos.index).ffill().dropna()
        if len(idx) > 20:
            idx_perf = _perf(idx.pct_change())
            metrics["oos_index"] = idx_perf
            checks.append(("Beats the index, total return",
                           strat_oos["total_pct"] > idx_perf["total_pct"],
                           f"{strat_oos['total_pct']:+.1f}% vs index {idx_perf['total_pct']:+.1f}%"))

    bt = scoring.backtest(score.reindex(oos.index), close.reindex(oos.index), cfg.forward_days, cfg)
    p = bt.get("p_bootstrap", float("nan"))
    metrics["oos_backtest"] = bt
    checks.append(("Not explained by luck", _finite(p) and p < desk_cfg.p_threshold,
                   f"bootstrap p = {p:.2f} (need < {desk_cfg.p_threshold:.2f})" if _finite(p)
                   else "too few independent windows for a p-value"))

    entries = metrics["oos_entries"]
    checks.append(("Traded enough to judge", entries >= desk_cfg.min_entries,
                   f"{entries} entries (need {desk_cfg.min_entries})"))

    passed = all(ok for _, ok, _ in checks)
    metrics["checks"] = checks
    metrics["passed"] = passed

    args = [Argument("bull" if ok else "bear", name, detail, 0.0, False, "Backtest Gate")
            for name, ok, detail in checks]
    if passed:
        summary = (f"Passed. On {len(oos)} unseen days the score returned "
                   f"{strat_oos['total_pct']:+.1f}% vs {hold_oos['total_pct']:+.1f}% holding, after costs.")
    else:
        failed = [name.lower() for name, ok, _ in checks if not ok]
        summary = "Blocked: " + "; ".join(failed) + "."
    return AgentReport("Backtest Gate", "Out-of-sample test", "bull" if passed else "bear",
                       summary, args, metrics)


# ----------------------------------------------------------------------
# THE CHIEF: ruling + paper ticket
# ----------------------------------------------------------------------
def chief_ruling(composite: dict, gate: AgentReport, risk: AgentReport,
                 bull: AgentReport, bear: AgentReport,
                 cfg: scoring.ScoringConfig = scoring.CFG,
                 desk_cfg: DeskConfig = DESK_CFG) -> dict:
    """Rules from the formula and the gate. Advocates explain; they do not vote."""
    final = composite.get("final")
    reading = composite.get("reading", "Not enough data")
    passed = bool(gate.metrics.get("passed"))
    bull_s, bear_s = bull.metrics.get("strength", 0.0), bear.metrics.get("strength", 0.0)
    louder = "bull" if bull_s > bear_s else "bear" if bear_s > bull_s else "neither"

    ticket = None
    if not _finite(final):
        decision, tone = "No ruling", "neutral"
        why = "The composite score could not be computed, so there is nothing to rule on."
    elif not passed:
        decision, tone = "No trade. Hold the index.", "neutral"
        why = (f"Your score reads {final:+.2f} sigma ({reading.lower()}), but it did not beat "
               "the benchmark on data it never saw. Without an out-of-sample edge, the honest "
               "default is a low-cost index fund rather than this stock.")
    elif final >= cfg.mild_threshold:
        decision, tone = "Paper-trade candidate", "bull"
        why = (f"Score {final:+.2f} sigma ({reading.lower()}) and the gate passed. Worth a paper "
               "trade at the risk manager's size. Not an instruction to buy.")
        size = risk.metrics.get("position_pct")
        if size is not None:
            ticket = {
                "side": "Long (paper)",
                "reference_price": risk.metrics.get("price"),
                "stop_price": risk.metrics.get("stop_price"),
                "position_pct": size,
                "risk_pct": desk_cfg.risk_per_trade_pct,
            }
    elif final <= -cfg.mild_threshold:
        decision, tone = "Avoid / reduce", "bear"
        why = (f"Score {final:+.2f} sigma ({reading.lower()}) and the gate passed, so weak "
               "readings have historically meant weak returns here. Not a short instruction.")
    else:
        decision, tone = "No clear tilt", "neutral"
        why = f"Score {final:+.2f} sigma sits inside ±{cfg.mild_threshold:.1f}: nothing to act on."

    agreement = None
    if louder != "neither" and _finite(final):
        formula_side = _stance(final, cfg)
        if formula_side != "neutral":
            agreement = (louder == formula_side)

    return {
        "decision": decision, "tone": tone, "why": why, "final": final,
        "reading": reading, "gate_passed": passed,
        "bull_strength": bull_s, "bear_strength": bear_s, "louder_side": louder,
        "advocates_agree_with_formula": agreement, "ticket": ticket,
    }


def run_desk(*, daily_df: pd.DataFrame, indicator_frame: pd.DataFrame,
             tech_score_series: pd.Series, penalty_series: pd.Series,
             composite: dict, sentiment_sigma: float | None, sentiment_info: dict | None,
             fundamentals: dict | None, index_close: pd.Series | None = None,
             cfg: scoring.ScoringConfig = scoring.CFG,
             desk_cfg: DeskConfig = DESK_CFG) -> dict:
    """Runs all seven agents and the Chief. Returns reports in speaking order."""
    weights_used = composite.get("weights_used", {}) or {}
    technical = composite.get("technical")
    price = float(daily_df["Close"].dropna().iloc[-1]) if len(daily_df) else None
    penalty = float(composite.get("risk_penalty") or 0.0)

    tape = tape_reader(indicator_frame, technical, weights_used, cfg)
    fundies = fundamentals_analyst(fundamentals or {}, price)
